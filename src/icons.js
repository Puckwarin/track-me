function escAttr(v) {
  return String(v ?? '').replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

function resolveEntry(nameOrClass = '') {
  const raw = String(nameOrClass || '').trim();
  if (!raw) return { svg: squaresFour, spin: false };
  const tokens = raw.split(/\s+/);
  const spin = tokens.includes('fa-spin');
  const iconToken = tokens.find(t => t !== 'fa-solid' && t !== 'fa-regular' && t !== 'fa-spin') || raw;
  return { svg: ICONS[iconToken] || ICONS[raw] || squaresFour, spin };
}

function extractSvgInner(rawSvg) {
  const s = String(rawSvg || '');
  const openEnd = s.indexOf('>');
  const closeStart = s.lastIndexOf('</svg>');
  if (openEnd < 0 || closeStart <= openEnd) return s;
  return s.slice(openEnd + 1, closeStart);
}

export function iconSvg(name, { size = 18, className = '' } = {}) {
  const { svg, spin } = resolveEntry(name);
  const clsParts = ['tm-svg-icon', 'ph-duotone'];
  if (spin) clsParts.push('animate-spin');
  if (className) clsParts.push(className);
  return `<svg class="${escAttr(clsParts.join(' '))}" width="${size}" height="${size}" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">${extractSvgInner(svg)}</svg>`;
}

export function iconBubble(name, { small = false, cat = '', size } = {}) {
  const iconSize = size ?? (small ? 18 : 22);
  const cls = ['emoji-bubble', 'icon-bubble'];
  if (small) cls.push('emoji-sm');
  if (cat) cls.push(cat);
  return `<span class="${cls.join(' ')}" aria-hidden="true">${iconSvg(name, { size: iconSize })}</span>`;
}
