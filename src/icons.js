function escAttr(v) {
  return String(v ?? '').replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

function resolveLucideEntry(nameOrClass = '') {
  const raw = String(nameOrClass || '').trim();
  if (!raw) return { icon: LayoutGrid, spin: false };
  const tokens = raw.split(/\s+/);
  const spin = tokens.includes('fa-spin');
  const iconToken = tokens.find(t => t !== 'fa-solid' && t !== 'fa-regular' && t !== 'fa-spin') || raw;
  return { icon: ICONS[iconToken] || ICONS[raw] || LayoutGrid, spin };
}

function renderNodes(nodes) {
  return (nodes || []).map(([tag, attrs]) => {
    const attrStr = Object.entries(attrs || {})
      .map(([k, v]) => `${k}="${escAttr(v)}"`)
      .join(' ');
    return `<${tag}${attrStr ? ' ' + attrStr : ''}/>`;
  }).join('');
}

export function iconSvg(name, { size = 18, className = '', strokeWidth = 1.85 } = {}) {
  const { icon, spin } = resolveLucideEntry(name);
  const clsParts = ['tm-svg-icon', 'lucide'];
  if (spin) clsParts.push('animate-spin');
  if (className) clsParts.push(className);
  return `<svg class="${escAttr(clsParts.join(' '))}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${renderNodes(icon)}</svg>`;
}

export function iconBubble(name, { small = false, cat = '', size } = {}) {
  const iconSize = size ?? (small ? 17 : 21);
  const cls = ['emoji-bubble', 'icon-bubble'];
  if (small) cls.push('emoji-sm');
  if (cat) cls.push(cat);
  return `<span class="${cls.join(' ')}" aria-hidden="true">${iconSvg(name, { size: iconSize })}</span>`;
}
